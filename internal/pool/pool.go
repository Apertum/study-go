// Package pool переиспользует «тяжёлые» объекты вместо новых аллокаций.
//
// Пул хранит объекты одного конкретного типа, который умеет сбрасывать собственное
// состояние методом Reset — такие методы выводит go run ./cmd/reset. Сброс выполняет
// сам Put, поэтому вернуть в пул объект с чужими данными нельзя:
//
//	p := pool.New[*resetdemo.ResetableStruct]()
//	object := p.Get() // объект со сброшенным состоянием
//	// ... заполняем поля ...
//	p.Put(object)     // Reset внутри Put
//	object = p.Get()  // тот же экземпляр либо новый, но снова чистый
//
// Рабочая форма — пул указателя, потому что генератор объявляет Reset на
// указателе-получателе, и под ограничение Reseter попадает только *Т.
//
// Пул создают конструктором New и передают только по указателю: внутри лежит
// sync.Pool, копирование которого находит go vet. Использовать объект после Put
// нельзя — пул не следит за правом собственности, и один экземпляр имеют право
// выдать повторно.
package pool

import (
	"reflect"
	"sync"
)

// Reseter — объект, сбрасывающий собственное состояние в нулевое.
type Reseter interface{ Reset() }

// Pool хранит объекты одного типа T и отдаёт их только со сброшенным состоянием.
// Нулевое значение пула нерабочее: создавать пул нужно конструктором New.
type Pool[T Reseter] struct {
	alloc func() T
	isNil func(T) bool
	pool  sync.Pool
}

const (
	unsupportedTypeParam = "pool: параметр типа должен быть структурой или указателем на структуру"
	wrongStoredType      = "pool: значение в пуле имеет тип, отличный от параметра типа"
)

// New создаёт пустой пул объектов типа T.
//
// Способ создать новый объект выводится из T один раз здесь и вызывается только
// тогда, когда в пуле ничего не осталось. Паникует, если T — интерфейс: нового
// объекта для интерфейсного типа не существует, а ошибки у конструктора нет.
func New[T Reseter]() *Pool[T] {
	var zero T

	objectType := reflect.TypeFor[T]()
	if objectType.Kind() == reflect.Interface {
		panic(unsupportedTypeParam)
	}

	isPointer := objectType.Kind() == reflect.Pointer

	created := &Pool[T]{
		// Nil указателя — сравнение двух значений any с одним динамическим типом: без
		// рефлексии на каждый Put и без аллокаций. У вида-значения nil быть не может, а
		// сравнение структуры со слайсом или картой паникует, поэтому сравнение включено
		// только для указателя.
		isNil: func(object T) bool { return isPointer && any(object) == any(zero) },
	}

	if isPointer {
		element := objectType.Elem()
		created.alloc = func() T {
			var object T
			// Приведение `any` к параметру типа потребовало бы проверки типов, поэтому
			// значение пишется в переменную типа T через отражение.
			reflect.ValueOf(&object).Elem().Set(reflect.New(element))

			return object
		}
	} else {
		created.alloc = func() T { return zero }
	}

	created.pool.New = func() any { return created.alloc() }

	return created
}

// Get возвращает объект из пула: переиспользованный либо вновь созданный, если пул пуст.
// Результат никогда не бывает nil и всегда отдаётся со сброшенным состоянием,
// потому что сброс выполнен предыдущим Put.
//
// Пул заполняет хранилище только значениями типа T, поэтому значение другого типа
// означает повреждение хранилища и проявляется сразу, а не молчаливым nil из Get.
func (p *Pool[T]) Get() T {
	object, ok := p.pool.Get().(T)
	if !ok {
		panic(wrongStoredType)
	}

	return object
}

// Put сбрасывает состояние объекта и возвращает его в пул.
//
// Вызывающей стороне Reset вызывать не нужно. Nil-аргумент, включая nil-указатель
// конкретного типа, отбрасывается: пул не начнёт отдавать nil. После Put обращаться
// к объекту нельзя — он передан пулу.
func (p *Pool[T]) Put(object T) {
	if p.isNil(object) {
		return
	}

	object.Reset()
	p.pool.Put(object)
}
