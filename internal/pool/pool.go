// Package pool переиспользует «тяжёлые» объекты вместо новых аллокаций.
//
// Пул хранит объекты одного конкретного типа, который умеет сбрасывать собственное
// состояние методом Reset — такие методы выводит go run ./cmd/reset. Сброс выполняет
// сам Put, поэтому вернуть в пул объект с чужими данными нельзя:
//
//	// Новый объект создаёт вызывающий код: здесь нужен буфер заданного размера, в другом
//	// месте — клиент с настроенными таймаутами:
//	sessions := pool.New(func() *Session { return &Session{body: make([]byte, 0, sessionSize)} })
//	object := sessions.Get() // объект со сброшенным состоянием
//	// ... заполняем поля ...
//	sessions.Put(object)     // Reset внутри Put
//	object = sessions.Get()  // тот же экземпляр либо новый, но снова чистый
//
// Конструктор newFn — та же точка расширения, что поле New у sync.Pool: он вызывается только
// когда в пуле ничего не осталось, и на штатном пути Get/Put не участвует. Его можно и не
// передавать — тогда, как у sync.Pool с пустым New, получение из пустого пула отдаёт нулевое
// значение типа T (nil для указателя, пустую структуру для вида-значения), и объект создаёт
// вызывающая сторона.
//
// Рабочая форма — пул указателя, потому что генератор объявляет Reset на
// указателе-получателе, и под ограничение Reseter попадает только *Т.
//
// Пул создают конструктором New и передают только по указателю: внутри лежит
// sync.Pool, копирование которого находит go vet. Использовать объект после Put
// нельзя — пул не следит за правом собственности, и один экземпляр имеют право
// выдать повторно.
package pool

import (
	"reflect"
	"sync"
)

// Reseter — объект, сбрасывающий собственное состояние в нулевое.
type Reseter interface{ Reset() }

// Pool хранит объекты одного типа T и отдаёт их только со сброшенным состоянием.
// Нулевое значение пула нерабочее: создавать пул нужно конструктором New.
type Pool[T Reseter] struct {
	isNil func(T) bool
	pool  sync.Pool
}

const (
	unsupportedTypeParam = "pool: параметр типа должен быть структурой или указателем на структуру"
	wrongStoredType      = "pool: значение в пуле имеет тип, отличный от параметра типа"
)

// New создаёт пустой пул объектов типа T.
//
// newFn задаёт способ создать новый объект и вызывается только тогда, когда в пуле ничего не
// осталось. Нулевой newFn допустим и повторяет контракт sync.Pool с пустым полем New: способ
// создать объект отсутствует, поэтому Get отдаёт нулевое значение типа T — nil для указателя,
// пустую структуру для вида-значения. Так же обрабатывается и newFn, вернувший nil.
//
// Паникует, если T — интерфейс: ошибки у конструктора нет, а нулевой аргумент возврата
// интерфейсного значения нельзя определить сравнением.
func New[T Reseter](newFn func() T) *Pool[T] {
	objectType := reflect.TypeFor[T]()
	if objectType.Kind() == reflect.Interface {
		panic(unsupportedTypeParam)
	}

	var zero T
	isPointer := objectType.Kind() == reflect.Pointer

	created := &Pool[T]{
		// Nil указателя — сравнение двух значений any с одним динамическим типом: без
		// рефлексии на каждый Put и без аллокаций. У вида-значения nil быть не может, а
		// сравнение структуры со слайсом или картой паникует, поэтому сравнение включено
		// только для указателя.
		isNil: func(object T) bool { return isPointer && any(object) == any(zero) },
	}

	// Хранилище остаётся без New ровно как у sync.Pool: nil вместо объекта означает «создавать
	// нечего», и Get вернёт нулевое значение.
	if newFn != nil {
		created.pool.New = func() any {
			object := newFn()
			if created.isNil(object) {
				return nil
			}

			return object
		}
	}

	return created
}

// Get возвращает объект из пула: переиспользованный либо вновь созданный, если пул пуст.
// Переиспользованный экземпляр всегда отдаётся со сброшенным состоянием, потому что сброс
// выполнен предыдущим Put; новый объект приходит таким, каким его сделал newFn.
//
// Если способ создать объект не передан (или он вернул nil), возвращается нулевое значение
// типа T — как у sync.Pool с пустым New. Вызывающая сторона, которой нужен объект, проверяет
// результат и создаёт его сама.
//
// Пул заполняет хранилище только значениями типа T, поэтому значение другого типа
// означает повреждение хранилища и проявляется сразу.
func (p *Pool[T]) Get() T {
	var zero T

	stored := p.pool.Get()
	if stored == nil {
		return zero
	}

	// Приведение с проверкой: чужой тип должен давать панику с именем пакета и причиной,
	// а не сообщение runtime о недопустимом приведении.
	object, ok := stored.(T)
	if !ok {
		panic(wrongStoredType)
	}

	return object
}

// Put сбрасывает состояние объекта и возвращает его в пул.
//
// Вызывающей стороне Reset вызывать не нужно. Nil-аргумент, включая nil-указатель
// конкретного типа, отбрасывается: пул не начнёт отдавать nil. После Put обращаться
// к объекту нельзя — он передан пулу.
func (p *Pool[T]) Put(object T) {
	if p.isNil(object) {
		return
	}

	object.Reset()
	p.pool.Put(object)
}
