// Package resetgen генерирует метод Reset для структур, помеченных комментарием generate:reset.
//
// Сброс готовит объект к повторному использованию, не освобождая память: скалярные поля
// обнуляются, слайсы обрезаются до [:0], map очищаются clear, каналы и функции обнуляются,
// указатель сбрасывает значение по указателю без смены адреса, а вложенные объекты делегируют
// сброс собственному методу Reset. Полный перечень видов поля и ограничений описан в
// документации команды cmd/reset.
//
// Генерация не трогает файлы: Generate возвращает пути и содержимое в памяти, на диск пишет
// вызывающая сторона.
package resetgen

import (
	"errors"
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	// Directive — комментарий над объявлением структуры, помечающий её целевой.
	Directive = "generate:reset"
	// GeneratedSuffix — суффикс генерируемого файла: <исходник>_reset_gen.go.
	GeneratedSuffix = "_reset_gen.go"
	// GeneratedHeader — преамбула сгенерированного файла: предупреждение не редактировать
	// вручную. Файл принадлежит генератору по имени (GeneratedSuffix), а не по этой строке.
	GeneratedHeader = "// Code generated by \"reset\". DO NOT EDIT."
	// resetMethod — имя генерируемого метода.
	resetMethod = "Reset"
)

// Warning сообщает о пропущенном поле или типе. Генерация из-за него не прерывается.
//
// Поля упорядочены так, чтобы указатели шли в начале структуры: это требование fieldalignment из
// набора проверок cmd/staticlint.
type Warning struct {
	Message  string
	Position token.Position
}

func (w Warning) String() string {
	return w.Position.String() + ": " + w.Message
}

// File — сгенерированный файл: путь к нему и содержимое.
type File struct {
	Path    string
	Content []byte
}

// GeneratedPath возвращает путь файла, который генератор ведёт для исходника.
func GeneratedPath(sourcePath string) string {
	return strings.TrimSuffix(sourcePath, ".go") + GeneratedSuffix
}

// loadMode — сведения о пакете, без которых генератор не работает: имя, файлы, типы, дерево
// разбора и соответствие выражений типам. Импортные зависимости нужны, чтобы видеть методы чужих
// типов.
var loadMode = packages.NeedName | packages.NeedFiles | packages.NeedTypes | packages.NeedSyntax |
	packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps

// Load разбирает пакеты по паттернам формы go list (./..., явные пути). Без паттернов — текущий
// каталог. Пакет с ошибками разбора считается ошибкой загрузки: частично сгенерированных файлов
// быть не должно.
func Load(dir string, patterns ...string) ([]*packages.Package, error) {
	if len(patterns) == 0 {
		patterns = []string{"."}
	}

	pkgs, err := packages.Load(&packages.Config{Mode: loadMode, Dir: dir}, patterns...)
	if err != nil {
		return nil, fmt.Errorf("загрузка пакетов: %w", err)
	}

	var broken []error
	for _, pkg := range pkgs {
		for _, pkgErr := range pkg.Errors {
			broken = append(broken, fmt.Errorf("%s: %s", pkg.PkgPath, pkgErr))
		}
	}
	if len(broken) > 0 {
		return nil, errors.Join(broken...)
	}
	return pkgs, nil
}

// fileTargets — цели генерации одного исходного файла.
type fileTargets struct {
	pkg     *packages.Package
	src     *ast.File
	targets []target
}

// Generate строит содержимое файлов с методами Reset для набора пакетов.
//
// Генерация в два прохода. Первый собирает все помеченные типы: метод у них появится только в
// результате второго прохода, а делегировать сброс дочернему типу нужно уже сейчас — иначе поле
// вида child *ResetableStruct осталось бы необработанным. Второй проход рендерит файлы, зная,
// для каких типов Reset() будет создан.
//
// Предупреждения о пропущенных полях возвращаются отсортированными по позиции, запись на диск
// не выполняется.
func Generate(pkgs []*packages.Package) ([]File, []Warning, error) {
	var (
		warnings   []Warning
		scanned    []fileTargets
		resettable = make(map[string]bool)
	)

	for _, pkg := range pkgs {
		for _, src := range sortFiles(pkg) {
			targets := scan(pkg, src, &warnings)
			if len(targets) == 0 {
				continue
			}
			for _, item := range targets {
				resettable[typeKey(item.named)] = true
			}
			scanned = append(scanned, fileTargets{pkg: pkg, src: src, targets: targets})
		}
	}

	files := make([]File, 0, len(scanned))
	for _, item := range scanned {
		content, err := render(item.pkg, item.src, item.targets, resettable, &warnings)
		if err != nil {
			return nil, warnings, err
		}
		files = append(files, File{Path: GeneratedPath(sourcePath(item.pkg, item.src)), Content: content})
	}

	sortWarnings(warnings)
	return files, warnings, nil
}

// typeKey — ключ именованного типа: путь пакета и имя. Один и тот же тип в разных разобранных
// пакетах может быть представлен разными объектами, поэтому указатели сравнивать нельзя.
func typeKey(named *types.Named) string {
	obj := named.Obj()
	if obj.Pkg() == nil {
		return obj.Name()
	}
	return obj.Pkg().Path() + "." + obj.Name()
}

// sortFiles упорядочивает файлы пакета по пути: порядок типов в выводе должен быть детерминированным,
// а packages не обещает порядка Syntax. Тестовые файлы — не цели генерации.
func sortFiles(pkg *packages.Package) []*ast.File {
	files := make([]*ast.File, 0, len(pkg.Syntax))
	for _, file := range pkg.Syntax {
		if strings.HasSuffix(sourcePath(pkg, file), "_test.go") {
			continue
		}
		files = append(files, file)
	}
	sort.Slice(files, func(i, j int) bool { return sourcePath(pkg, files[i]) < sourcePath(pkg, files[j]) })
	return files
}

func sourcePath(pkg *packages.Package, file *ast.File) string {
	return pkg.Fset.Position(file.Pos()).Filename
}

func sortWarnings(warnings []Warning) {
	sort.Slice(warnings, func(i, j int) bool {
		left, right := warnings[i].Position, warnings[j].Position
		if left.Filename != right.Filename {
			return left.Filename < right.Filename
		}
		return left.Line < right.Line
	})
}
