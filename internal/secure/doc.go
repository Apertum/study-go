// Package secure выпускает самоподписанный материал TLS, переиспользует его между
// запусками, собирает конфигурацию TLS сервера и клиента и отдаёт обработчик
// редиректа с HTTP на HTTPS.
//
// Флаги и переменные окружения (переменная переопределяет флаг, флаг — файл конфигурации,
// подробности — `go doc ./internal/config`):
//
//	-s                     | ENABLE_HTTPS          — включить HTTPS (разбирает config.ParseFlags, ключ файла enable_https)
//	-cert-file             | CERT_FILE             — сертификат, по умолчанию cert.pem
//	-key-file              | KEY_FILE              — закрытый ключ, по умолчанию key.pem
//	-http-addr             | HTTP_SERVER_ADDRESS   — адрес редиректа, по умолчанию :8081
//
// Запуск:
//
//	go run ./cmd/shorter -s
//	go run ./cmd/shortener -addr localhost:8080 -s -cert-file cert.pem
//	curl --cacert cert.pem https://localhost:8080/ping
//
// Сервер выпускает сертификат на ECDSA P-256 со сроком действия год и пишет пару
// файлов: сертификат с правами 0644, закрытый ключ с правами 0600. Ни закрытый ключ,
// ни его фрагменты не попадают ни в один лог и ни в одно сообщение об ошибке —
// в диагностике только пути и причина. Минимальная версия протокола — TLS 1.2,
// TLS 1.3 согласуется автоматически.
//
// Проверка сертификата у клиента не отключается никогда: InsecureSkipVerify не
// используется ни в одном режиме, а доверие к самоподпису добавляется точечно —
// ровно одним сертификатом из CERT_FILE в собственный пул RootCAs. Системные
// корни при этом не расширяются. Самоподписанный сертификат годится для локального
// и внутреннего контура; для публичного эндпоинта нужен сертификат от внешней CA.
//
// Ограничение: адрес редиректа отвечает 301, а часть клиентов повторяет после
// него POST как GET без тела. В API ходите сразу на https:// — адрес редиректа
// предназначен для людей и старых клиентов, которые помнят только открытый HTTP.
