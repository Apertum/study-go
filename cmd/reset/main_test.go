package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestRunCreatesFiles проверяет первый запуск: файл создан рядом с исходником, путь напечатан.
func TestRunCreatesFiles(t *testing.T) {
	dir := moduleFixture(t)
	t.Chdir(dir)

	var stdout bytes.Buffer
	if got := run(&stdout); got != exitOK {
		t.Fatalf("первый запуск вернул код %d, вывод: %s", got, stdout.String())
	}

	content := readFile(t, generatedName)
	if !strings.Contains(content, "func (b *Box) Reset()") {
		t.Fatalf("в файле нет метода Reset:\n%s", content)
	}
	if !strings.Contains(stdout.String(), statusWritten) || !strings.Contains(stdout.String(), generatedName) {
		t.Errorf("вывод = %q, хотим упоминание о записи %s", stdout.String(), generatedName)
	}
}

// TestRunOverwritesForeignFile: файл с нашим именем принадлежит генератору независимо от того,
// кто его написал — содержимое не читается и не сравнивается.
func TestRunOverwritesForeignFile(t *testing.T) {
	dir := moduleFixture(t)
	writeFile(t, filepath.Join(dir, generatedName), "// писано рукой, без преамбулы\n\npackage box\n")
	t.Chdir(dir)

	var stdout bytes.Buffer
	if got := run(&stdout); got != exitOK {
		t.Fatalf("запуск вернул код %d, вывод: %s", got, stdout.String())
	}
	content := readFile(t, generatedName)
	if !strings.HasPrefix(content, "// Code generated by") {
		t.Errorf("файл не перезаписан выводом генератора:\n%s", content)
	}
	if !strings.Contains(stdout.String(), statusWritten) {
		t.Errorf("вывод = %q, хотим упоминание о записи %s", stdout.String(), generatedName)
	}
}

// TestRunRewritesFilesEveryTime: повторный запуск пишет файл заново и называет его в выводе,
// но содержимое остаётся прежним — вывод генератора детерминирован.
func TestRunRewritesFilesEveryTime(t *testing.T) {
	dir := moduleFixture(t)
	t.Chdir(dir)

	var first bytes.Buffer
	if got := run(&first); got != exitOK {
		t.Fatalf("первый запуск вернул код %d", got)
	}
	want := readFile(t, generatedName)

	var second bytes.Buffer
	if got := run(&second); got != exitOK {
		t.Fatalf("повторный запуск вернул код %d, вывод: %s", got, second.String())
	}
	if !strings.Contains(second.String(), generatedName) || !strings.Contains(second.String(), statusWritten) {
		t.Errorf("вывод = %q, хотим файл %s со статусом %q", second.String(), generatedName, statusWritten)
	}
	if got := readFile(t, generatedName); got != want {
		t.Errorf("содержимое файла изменилось:\n%s", got)
	}
}

// TestRunRegeneratesAfterEdit: новое поле исходника попадает в метод при обычном запуске —
// предварительно проверять актуальность не нужно.
func TestRunRegeneratesAfterEdit(t *testing.T) {
	dir := moduleFixture(t)
	t.Chdir(dir)

	var first bytes.Buffer
	if got := run(&first); got != exitOK {
		t.Fatalf("первый запуск вернул код %d", got)
	}

	writeFile(t, filepath.Join(dir, "box.go"), "package box\n\n//generate:reset\ntype Box struct {\n\tn int\n\ts []string\n}\n")

	var stdout bytes.Buffer
	if got := run(&stdout); got != exitOK {
		t.Fatalf("второй запуск вернул код %d, вывод: %s", got, stdout.String())
	}
	body := readFile(t, generatedName)
	if !strings.Contains(body, "b.s = b.s[:0]") {
		t.Errorf("новое поле не попало в метод:\n%s", body)
	}
	if !strings.Contains(stdout.String(), statusWritten) {
		t.Errorf("вывод = %q, хотим упоминание о записи", stdout.String())
	}
}

// TestRunDeletesOrphaned: с директивой остался только несуществующий тип — файл удаляется,
// иначе в пакете останется метод на несуществующий тип.
func TestRunDeletesOrphaned(t *testing.T) {
	dir := moduleFixture(t)
	t.Chdir(dir)

	var first bytes.Buffer
	if got := run(&first); got != exitOK {
		t.Fatalf("первый запуск вернул код %d", got)
	}

	writeFile(t, filepath.Join(dir, "box.go"), "package box\n\ntype Box struct {\n\tn int\n}\n")

	var stdout bytes.Buffer
	if got := run(&stdout); got != exitOK {
		t.Fatalf("запуск без помеченных типов вернул код %d, вывод: %s", got, stdout.String())
	}
	if _, err := os.Stat(generatedName); !os.IsNotExist(err) {
		t.Errorf("файл не удалён после снятия директивы: %v", err)
	}
	if !strings.Contains(stdout.String(), statusRemoved) {
		t.Errorf("вывод = %q, хотим упоминание об удалении", stdout.String())
	}
}

// TestRunLeavesNoPartialFiles: пакет разбирается с ошибкой — ни одного выходного файла появиться
// не должно, даже если часть исходников пакета генератор успел бы обработать.
func TestRunLeavesNoPartialFiles(t *testing.T) {
	dir := moduleFixture(t)
	writeFile(t, filepath.Join(dir, "broken.go"), "package box\n\nfunc Broken() { this is not go\n")
	t.Chdir(dir)

	var stdout bytes.Buffer
	if got := run(&stdout); got != exitFailure {
		t.Errorf("код возврата = %d, хотим %d; вывод: %s", got, exitFailure, stdout.String())
	}
	if _, err := os.Stat(generatedName); !os.IsNotExist(err) {
		t.Errorf("файл создан несмотря на ошибку разбора пакета: %v", err)
	}
}

const generatedName = "box_reset_gen.go"

// moduleFixture создаёт отдельный модуль с одним помеченным типом: команде нужен настоящий
// пакет, который способен разобрать go list.
func moduleFixture(t *testing.T) string {
	t.Helper()

	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module resetfixture\n\ngo 1.26.0\n")
	writeFile(t, filepath.Join(dir, "box.go"), "package box\n\n//generate:reset\ntype Box struct {\n\tn int\n}\n")

	return dir
}
