// Command reset генерирует метод Reset для структур, помеченных комментарием generate:reset.
//
// Сброс готовит объект к повторному использованию, не освобождая память: скаляры обнуляются,
// слайсы обрезаются до нулевой длины, карты очищаются, значение по указателю обнуляется без смены
// адреса, а вложенные объекты сбрасываются собственным методом Reset.
//
// # Директива
//
// Комментарий generate:reset размещается непосредственно над объявлением структуры. Пробел после
// "//" и регистр не значимы, поэтому допустимы и //generate:reset, и // Generate:RESET.
// Комментарий над блоком type ( ... ) ни один тип не помечает — директиву нужно ставить над
// конкретным объявлением, о чём генератор предупреждает.
//
//	//generate:reset
//	type ResetableStruct struct {
//		i     int
//		str   string
//		strP  *string
//		s     []int
//		m     map[string]string
//		child *ResetableStruct
//	}
//
// # Вид поля и сгенерированный код
//
//	scalars:   int, float64, string, bool, complex64  ->  pole = 0 / "" / false / 0i
//	aliases:   type Name string, type IDs []int       ->  как исходный вид поля
//	slices:    pole = pole[:0]
//	maps:      clear(pole)
//	arrays:    pole = [N]T{}
//	chans/func: pole = nil
//	pointer:   if pole != nil { <правило для значения по указателю> }
//	nested:    pole.Reset() под проверкой на nil, если у типа поля есть Reset()
//	iface:     if value, ok := pole.(interface{ Reset() }); ok && value != nil { value.Reset() }
//	embedded:  по имени встроенного типа, как обычное поле
//	skipped:   структура без Reset(), unsafe.Pointer, generic-структура -> предупреждение
//
// Указатель снимается рекурсивно: **int даёт вложенные проверки nil и обнуление значения на
// последнем уровне, а *[]int — срез по указателю. Присваивания nil самому полю генератор не
// делает, адрес результата остаётся прежним.
//
// # Ограничения
//
//   - Метод не генерируется для типа, который уже объявляет Reset с любым получателем — T или *T:
//     второе объявление метода Go запрещает. Встроенный метод (promotion) собственным не считается.
//   - Обход элементов контейнеров не генерируется: [:0] и clear затрагивают только контейнер.
//   - Память не освобождается: [:0] сохраняет ёмкость и лежащий за слайсом массив, clear делает
//     карту пригодной для записи, но не возвращает занятую память.
//   - Самоссылка (child *Self) корректна для дерева и списка, но на циклическом графе уходит в
//     бесконечную рекурсию — генератор предупреждает о риске на каждом таком поле.
//   - Generic-структуры не поддерживаются.
//
// # Запуск
//
//	go run ./cmd/reset        # перегенерировать методы во всём модуле
//
// Флагов и аргументов у команды нет: всегда разбирается ./..., а выходные файлы пишутся заново —
// совпадение с прошлым прогоном не повод его пропускать. Осиротевшие файлы удаляются. Проверять
// актуальность заранее не нужно: содержимое выходных файлов детерминировано, поэтому повторный
// запуск даёт те же байты.
//
// Коды возврата: 0 — файлы записаны, 1 — ошибка загрузки пакетов, генерации или записи.
// Диагностика идёт в stderr, список записанных и удалённых файлов — в stdout.
//
// # Судьба файлов
//
// Методы пишутся в <исходник>_reset_gen.go рядом с исходником. Файл принадлежит генератору по
// имени: любой файл с таким суффиксом из разобранных пакетов перезаписывается выводом генератора,
// а если помеченных типов не осталось — удаляется. Его содержимое не читается и ни с чем не
// сравнивается, поэтому ручная правка этих файлов обречена, как и собственный код под этим именем.
// Преамбула // Code generated by "reset". DO NOT EDIT. остаётся предупреждением человеку и
// маркером для редакторов, но не проверкой принадлежности.
//
// Пометить существующие типы из internal/model и internal/storage решено отдельным изменением,
// чтобы не смешивать генератор и правку рабочих моделей.
