// Command staticlint — единый инструмент статического анализа проекта,
// собранный на драйвере multichecker из golang.org/x/tools/go/analysis.
//
// Почти все правила — готовые анализаторы чужих проектов: инструмент собирает их и
// запускает одним проходом по пакетам. Одно правило собственное — noexit из пакета
// internal/analysis/noexit. Всю остальную работу — валидацию набора, разбор флагов,
// загрузку пакетов, вывод и коды возврата — выполняет multichecker.
//
// Запуск по всему проекту:
//
//	go run ./cmd/staticlint ./...
//
// # Состав
//
// Набор собран из пяти групп; всего 244 анализатора (для x/tools v0.51.0 и
// staticcheck v0.8.2 — точное число печатается при запуске в строке
// «зарегистрировано анализаторов»):
//
//   - 54 анализатора golang.org/x/tools/go/analysis/passes — аналог go vet;
//   - 26 анализаторов подпакета passes/modernize (modernize.Suite);
//   - 95 проверок класса SA, 35 класса S, 18 класса ST и 12 класса QF из
//     honnef.co/go/tools (staticcheck);
//   - 3 сторонних анализатора: nilerr, forcetypeassert, bodyclose;
//   - 1 собственный анализатор: noexit.
//
// Ниже перечислены все зарегистрированные проверки; формулировки взяты из их
// собственных Analyzer.Doc. Актуальную версию даёт встроенная справка, она же
// показывает флаги каждой проверки:
//
//	go run ./cmd/staticlint help             // все анализаторы с описаниями
//	go run ./cmd/staticlint help copylocks   // описание одной проверки
//
// # Механизм запуска multichecker
//
// main собирает срез анализаторов и вызывает multichecker.Main(analyzers...),
// после чего выполняется семь шагов.
//
// 1. Валидация набора (analysis.Validate). Проверяются уникальность имён,
// корректность ResultType/FactTypes и отсутствие циклов в графе Requires. Ошибка
// завершает процесс сразу через log.Fatal с кодом 1. Поэтому проверки staticcheck
// носят имена-коды (SA1000, S1002, ST1003, QF1002) — они не конфликтуют с
// именами анализаторов из passes.
//
// 2. Регистрация флагов драйвера (checker.RegisterFlags).
//
// 3. Регистрация флагов анализаторов и разбор командной строки
// (analysisflags.Parse(analyzers, true)). Каждый анализатор получает флаг-
// переключатель -NAME, а его собственные флаги публикуются с префиксом
// -NAME.<флаг> — например -printf.funcs или -shadow.strict. Флаг -NAME
// трёхсостоятельный: не указан — действует значение по умолчанию анализатора,
// -NAME=true включает проверку принудительно, -NAME=false исключает её из работы.
// Parse возвращает уже отфильтрованный список, который и передаётся драйверу.
//
// 4. Разбор позиционных аргументов. Без них печатается usage и процесс выходит с
// кодом 1. Первый аргумент help печатает справку по анализаторам и выходит с
// кодом 0.
//
// 5. Выбор режима исполнения. Если единственный аргумент оканчивается на .cfg,
// запускается unitchecker.Run: анализаторы работают в отдельном процессе над
// одним пакетом и обмениваются с родителем фактами через gob — именно так
// тулчейн запускает вет-подобные инструменты на большой сборке. Иначе
// запускается checker.Run — обычный режим, который загружает все перечисленные
// пакеты в текущем процессе.
//
// 6. Загрузка пакетов и построение графа анализа. checker.Run передаёт паттерны
// (./..., явные пути пакетов, отдельные .go-файлы) в go/packages, то есть
// фактически опрашивает «go list»: нужны корректный go.mod и собираемый код,
// потому что анализаторы работают по полной типизированной информации. Затем
// строится граф «пакет × анализатор», рёбра определяются полем Requires.
// Действия выполняются параллельно, а внутри зависимостей — последовательно;
// экспортные факты (FactTypes) передаются между пакетами, поэтому такие проверки,
// как printf, видят аннотации форматных функций в импортируемых пакетах. Флаг
// -test (по умолчанию включён) определяет, входят ли _test.go в загрузку, поэтому
// staticlint по умолчанию анализирует тесты вместе с основным кодом.
//
// 7. Вывод и коды возврата. Текстовые диагностики печатаются в stderr в виде
// «путь:строка:колонка: сообщение», где текст сообщения задаёт сам анализатор, а
// имя анализатора в него не входит (см. раздел «Как узнать, кто нашёл
// замечание»). С флагом -json диагностики уходят в stdout в машиночитаемом виде,
// где имя проверки присутствует. Коды возврата: 0 — замечаний нет; 1 — ошибка
// загрузки или хотя бы одна упавшая фаза анализа; 3 — анализ прошёл успешно и
// выдал замечания. С -json код всегда 0. Служебные сообщения logrus, которые
// настраивает config.LogsInit в init, пишутся в stderr и дублируются в
// logs/app.log; к кодам возврата анализа они отношения не имеют.
//
// # Флаги
//
// Флаги драйвера:
//
//   - -test=false — не анализировать тестовые файлы;
//   - -json — машиночитаемый вывод в stdout, с именем проверки;
//   - -c N — печатать N строк контекста вокруг проблемного места;
//   - -fix — применить все предложенные автоисправления;
//   - -diff — вместе с -fix не менять файлы, а показать unified diff;
//   - -flags — напечатать список флагов в JSON; -V — версию сборки;
//   - -debug fpstv, -cpuprofile, -memprofile, -trace — отладка и профилирование.
//
// Флаги анализаторов: -NAME включает или отключает проверку, -NAME.<флаг> задаёт
// её параметры. Примеры:
//
//	# игнорировать выравнивание полей и требование package comment
//	go run ./cmd/staticlint -fieldalignment=false -ST1000=false ./...
//
//	# искать затенение переменных строже (в том числе err внутри if)
//	go run ./cmd/staticlint -shadow.strict=true ./...
//
//	# без тестовых файлов, по три строки контекста на каждое замечание
//	go run ./cmd/staticlint -test=false -c 3 ./...
//
//	# посмотреть, что исправят автоисправления, и применить их
//	go run ./cmd/staticlint -diff -fix ./internal/...
//
// Для CI практично не переписывать список из двухсот флагов, а запускать tool с
// разными наборами отключений: жёсткий профиль выключает советнические классы QF
// и спорные правила ST, локальный прогон остаётся полным.
//
// # Как узнать, кто нашёл замечание
//
// В текстовом режиме имя анализатора не печатается — видно только сообщение.
// Способы установить автора замечания:
//
//   - запустить с -json: там есть имя проверки;
//   - выключать проверки флагами -NAME=false и сравнивать вывод;
//   - найти текст сообщения в каталоге ниже: в пределах класса он уникален.
//
// # Как добавить или убрать анализатор
//
// Убрать — флаг -NAME=false. Добавить — дописать импорт и элемент одного из срезов
